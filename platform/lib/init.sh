# shellcheck shell=bash
# One-time setup of /etc/ops, cron jobs, and clients of a backup server.

# Idempotent. Each run creates what is missing, stops at the first file you need
# to fill in, and once everything is in place checks every backup target.
cmd_init() {
  require_root
  load_ops_conf
  local generate=0 init_missing=0 target
  while (($#)); do
    case $1 in
      --generate-password) generate=1 ;;
      --init-missing) init_missing=1 ;;
      *) die "unknown option: $1" ;;
    esac
    shift
  done

  install -d -m 700 "$OPS_ETC"
  install -d -m 755 "$OPS_STATE" "$OPS_LOG_DIR"
  install -d -m 700 "$OPS_STAGE_ROOT" "$OPS_DATA_ROOT"

  if ! apps_need_backups; then
    log "no app backs up (every BACKUP_TARGETS is none); skipping restic setup"
    if [[ ! -f $OPS_ETC/alert.env ]]; then
      install -m 600 "$OPS_ROOT/platform/templates/alert.env.example" "$OPS_ETC/alert.env"
      die "created $OPS_ETC/alert.env from the template. Fill it in, then run ops init again"
    fi
    cmd_alert_test || die "fix alert.env, then run ops init again"
    log "init finished. Next: ops up <app> for each app"
    return
  fi

  if [[ ! -s $OPS_ETC/restic-password ]]; then
    if ((generate)); then
      (umask 077 && openssl rand -hex 32 >"$OPS_ETC/restic-password")
      log "generated $OPS_ETC/restic-password. Save a copy in your password manager and offline now"
    else
      die "write the restic password to $OPS_ETC/restic-password (mode 600) to reuse an existing one, or rerun with --generate-password"
    fi
  fi
  chmod 600 "$OPS_ETC/restic-password"

  if [[ ! -f $OPS_ETC/backup.env ]]; then
    install -m 600 "$OPS_ROOT/platform/templates/backup.env.example" "$OPS_ETC/backup.env"
    die "created $OPS_ETC/backup.env from the template. Fill it in, then run ops init again"
  fi
  chmod 600 "$OPS_ETC/backup.env"

  load_backup_env
  local targets
  targets=$(defined_targets)
  [[ -n $targets ]] || warn "backup.env defines no targets; apps can only use BACKUP_TARGETS=none"
  for target in $targets; do
    if restic_on "$target" cat config >/dev/null 2>&1; then
      log "target $target: repository is reachable"
    elif ((init_missing)); then
      restic_on "$target" init
      log "target $target: repository created"
    else
      die "target $target: repository is unreachable or does not exist. Fix backup.env, or rerun with --init-missing to create it"
    fi
  done

  if [[ ! -f $OPS_ETC/alert.env ]]; then
    install -m 600 "$OPS_ROOT/platform/templates/alert.env.example" "$OPS_ETC/alert.env"
    die "backups are ready. Created $OPS_ETC/alert.env from the template; fill it in, then run ops init again"
  fi
  chmod 600 "$OPS_ETC/alert.env"
  cmd_alert_test || die "fix alert.env, then run ops init again"
  log "init finished. Next: ops up <app> for each app, then ops install-cron"
}

apps_need_backups() {
  local app
  for app in $(list_apps); do
    load_app_conf "$app"
    [[ $BACKUP_TARGETS == none ]] || return 0
  done
  return 1
}

cmd_install_cron() {
  require_root
  load_ops_conf
  local ops=$OPS_ROOT/platform/bin/ops
  install -d -m 755 "$OPS_LOG_DIR"
  cat >/etc/cron.d/ops <<EOF
# Generated by ops install-cron from $OPS_CONF. Do not edit.
SHELL=/bin/bash
PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin
$BACKUP_TIME root $ops backup --all >>$OPS_LOG_DIR/backup.log 2>&1
$CHECK_TIME root $ops check >>$OPS_LOG_DIR/check.log 2>&1
EOF
  chmod 644 /etc/cron.d/ops
  cat >/etc/logrotate.d/ops <<EOF
$OPS_LOG_DIR/*.log {
    monthly
    rotate 12
    compress
    missingok
    notifempty
}
EOF
  log "installed /etc/cron.d/ops: backup at '$BACKUP_TIME', check at '$CHECK_TIME' (server time, $(date +%Z))"
}

# On a server that stores other servers' backups over SFTP: one locked-down
# user per client, so a compromised client can only reach its own repository.
cmd_backup_client() {
  require_root
  local action=${1:-} name=${2:-} key=${3:-} user dir
  [[ $action == add ]] || die "usage: ops backup-client add <name> '<ssh public key>'"
  [[ $name =~ ^[a-z0-9][a-z0-9-]*$ ]] || die "invalid client name: $name"
  [[ $key == ssh-* ]] || die "the third argument must be an SSH public key"
  user=backup-$name
  dir=/srv/backup/$name
  id "$user" >/dev/null 2>&1 || useradd -m -s /bin/bash "$user"
  install -d -m 700 -o "$user" -g "$user" "$(getent passwd "$user" | cut -d: -f6)/.ssh"
  # restrict: no shell features beyond what SFTP needs.
  printf 'restrict %s\n' "$key" >"$(getent passwd "$user" | cut -d: -f6)/.ssh/authorized_keys"
  chown "$user:$user" "$(getent passwd "$user" | cut -d: -f6)/.ssh/authorized_keys"
  chmod 600 "$(getent passwd "$user" | cut -d: -f6)/.ssh/authorized_keys"
  install -d -m 755 /srv/backup
  install -d -m 700 -o "$user" -g "$user" "$dir"
  log "client $name: repository sftp:$user@<this server>:$dir"
}
