# shellcheck shell=bash
# The edge Caddy: the only container that listens on 80 and 443.

edge_networks_file() { printf '%s/edge.networks.yaml' "$OPS_STATE"; }

# Every app with a compose file gets its own network, app-<name>. Only the edge
# joins all of them, so apps cannot reach each other.
app_network() { printf 'app-%s' "$1"; }

# Writes the compose override that attaches the edge to each app network.
# Generated rather than committed, so adding an app never edits platform files.
write_edge_networks() {
  local file app
  file=$(edge_networks_file)
  install -d -m 755 "$OPS_STATE"
  {
    echo "# Generated by ops. Do not edit."
    echo "services:"
    echo "  caddy:"
    echo "    networks:"
    echo "      - default"
    for app in $(list_apps); do
      app_has_compose "$app" && echo "      - $(app_network "$app")"
    done
    echo "networks:"
    echo "  default: {}"
    for app in $(list_apps); do
      app_has_compose "$app" && printf '  %s:\n    name: %s\n    external: true\n' "$(app_network "$app")" "$(app_network "$app")"
    done
  } >"$file.tmp"
  mv "$file.tmp" "$file"
}

edge_compose() {
  [[ -f $(edge_networks_file) ]] || write_edge_networks
  OPS_WWW_ROOT=$OPS_WWW_ROOT docker compose \
    --project-directory "$OPS_EDGE_DIR" \
    -f "$OPS_EDGE_DIR/compose.yaml" \
    -f "$(edge_networks_file)" "$@"
}

edge_running() {
  [[ -n $(edge_compose ps -q caddy 2>/dev/null) ]]
}

any_site() {
  local app
  for app in $(list_apps); do
    app_has_site "$app" && return 0
  done
  return 1
}

ensure_network() {
  docker network inspect "$1" >/dev/null 2>&1 || docker network create "$1" >/dev/null
}

edge_up() {
  local app
  for app in $(list_apps); do
    app_has_compose "$app" && ensure_network "$(app_network "$app")"
  done
  write_edge_networks
  edge_compose up -d --remove-orphans
}

# Attaches the running edge to one app network without restarting it. The
# override file keeps the attachment when the container is recreated later.
edge_attach() {
  local network=$1 container
  write_edge_networks
  edge_running || return 0
  container=$(edge_compose ps -q caddy)
  if ! docker inspect -f '{{json .NetworkSettings.Networks}}' "$container" | grep -q "\"$network\""; then
    docker network connect "$network" "$container"
  fi
}

edge_detach() {
  local network=$1 container
  write_edge_networks
  edge_running || return 0
  container=$(edge_compose ps -q caddy)
  docker network disconnect "$network" "$container" 2>/dev/null || true
}

# Validates first, so a broken file never survives until the next restart,
# when Caddy would refuse to start and take every site down.
cmd_reload_caddy() {
  require_root
  if ! edge_running; then
    if any_site; then
      log "edge is not running; starting it"
      edge_up
    fi
    return 0
  fi
  edge_compose exec -T caddy caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile </dev/null ||
    die "Caddy configuration is invalid; nothing was reloaded"
  edge_compose exec -T caddy caddy reload --config /etc/caddy/Caddyfile --adapter caddyfile </dev/null
  log "Caddy reloaded"
}
